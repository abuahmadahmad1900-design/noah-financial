    def simulate_attack(self):
        attack_type = random.choice(self.get_legendary_attacks())
        defense = random.choice(self.get_defenses())
        
        outcome = random.random()
        
        if outcome < 0.18:
            self.results["صد"] += 1
            result = "تم الصد"
        elif outcome < 0.36:
            self.results["امتصاص"] += 1
            result = "تم الامتصاص"
        elif outcome < 0.54:
            self.results["انعكاس"] += 1
            result = "انعكس الهجوم"
        elif outcome < 0.72:
            self.results["تحييد"] += 1
            result = "تم التحييد"
        elif outcome < 0.85:
            self.results["تجاهل"] += 1
            result = "تم التجاهل"
        elif outcome < 0.93:
            self.results["فشل"] += 1
            result = "فشل الاختراق"
        elif outcome < 0.96:
            self.results["إبادة"] += 1
            result = "تمت إبادة الهجوم"
        elif outcome < 0.98:
            self.results["تفكيك"] += 1
            result = "تم تفكيك الهجوم"
        elif outcome < 0.99:
            self.results["إلغاء"] += 1
            result = "تم إلغاء الهجوم"
        else:
            self.results["عزل"] += 1
            result = "تم عزل الهجوم"
        
