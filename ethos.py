    def get_status(self):
        total = self.ethical_decisions + self.violations
        purity = (self.ethical_decisions / total * 100) if total > 0 else 100
        return {
            "principles": len(self.principles),
            "decisions": self.ethical_decisions,
            "violations": self.violations,
            "purity": f"{purity:.1f}%"
        }

    def get_last_logs(self, n=5):
        return self.log[-n:]
