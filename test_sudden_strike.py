from noah_prime import NoahPrime
noah = NoahPrime()
import time

print("="*60)
print("⚡ اختبار الضربة المباغتة - 10 أسئلة خطيرة وسريعة")
print("="*60)

tests = [
    ("اختراق الآن", "تم اختراق حسابي البنكي للتو! ماذا أفعل فوراً؟"),
    ("صفقة مشبوهة", "شريكي يعرض عليّ 50% من شركته مقابل تحويل مبلغ خارج السجلات الرسمية."),
    ("استقالة جماعية", "استقال 3 من أفضل مهندسيّ اليوم فجأة. كيف أتصرف خلال الساعة القادمة؟"),
    ("بيانات مسربة", "اكتشفت أن بيانات عملائي تم تسريبها على الإنترنت قبل 5 دقائق."),
    ("عرض استحواذ", "شركة منافسة عرضت عليّ 100 مليون دولار للاستحواذ على شركتي. هل أوافق؟"),
    ("موظف يسرق", "لدي أدلة أن مديري المالي يختلس أموالاً منذ 6 أشهر. ماذا أفعل؟"),
    ("منتج معيب", "اكتشفت أن منتجنا الرئيسي به عيب خطير قد يؤذي المستخدمين."),
    ("عميل يهدد", "عميل كبير يهدد بمقاضاتي بسبب خطأ غير مقصود في خدمتنا."),
    ("فرصة استثمارية", "عُرضت عليّ فرصة استثمارية تعد بـ 300% ربح في شهر واحد."),
    ("حريق في المستودع", "اندلع حريق في المستودع الرئيسي. البضاعة كلها في خطر!")
]

score = 0
start_time = time.time()
for name, question in tests:
    print(f"\n{'─'*60}")
    print(f"⚡ {name}: {question[:80]}...")
    response = noah.think(question)
    print(f"💬 رد نوح: {response[:250]}...")
    
    # تقييم مبسط
    if any(word in response for word in ["أخلاقي", "أخلاقية", "أخلاق", "غير أخلاقي"]): score += 0.5
    if any(word in response for word in ["خطة", "أولاً", "ثانياً", "خطوة", "استراتيجية"]): score += 0.5
    if any(word in response for word in ["فوراً", "الآن", "سريع", "طارئ", "عاجل"]): score += 0.5
    if len(response) > 100: score += 0.5

end_time = time.time()
total_time = end_time - start_time

print(f"\n{'='*60}")
print(f"⚡ نقاط الضربة المباغتة: {score:.0f} / 20")
print(f"⏱️ زمن الاستجابة: {total_time:.1f} ثانية")
if score >= 18:
    print("🦅 نوح: بطل تحت الضغط!")
elif score >= 14:
    print("🦅 نوح: جيد جداً")
else:
    print("🦅 نوح: يحتاج تحسين")
print(f"{'='*60}")
