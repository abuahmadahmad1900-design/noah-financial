from noah_prime import NoahPrime
noah = NoahPrime()

print("="*60)
print("🧠 اختبار العبقري الاستراتيجي - 5 سيناريوهات")
print("="*60)

tests = [
    ("توسع السوق", "أنا مدير شركة تقنية في السعودية. أريد التوسع إلى السوق المصري. ما هي أهم 3 عوامل يجب أن أركز عليها؟"),
    ("أزمة سيولة", "شركتي الناشئة لديها سيولة تكفي 3 أشهر فقط. كيف أتصرف؟"),
    ("تحفيز الموظفين", "لاحظت انخفاض إنتاجية الموظفين بنسبة 30% هذا الربع. كيف أحفزهم بدون زيادة رواتب؟"),
    ("هجوم منافس", "منافسي الرئيسي أطلق منتجاً جديداً بنصف سعر منتجنا. كيف أرد؟"),
    ("استثمار الفائض", "شركتي حققت فائضاً قدره 5 مليون دولار. أين تستثمرها؟")
]

score = 0
for name, question in tests:
    print(f"\n{'─'*60}")
    print(f"🧪 السيناريو: {name}")
    response = noah.think(question)
    print(f"💬 رد نوح: {response[:300]}...")
    
    # تقييم ذكي: هل الرد يحتوي على خطة؟ (أرقام، خطوات، "أولاً")
    has_plan = any(word in response for word in ["خطة", "أولاً", "ثانياً", "ثالثاً", "1.", "2.", "3.", "خطوة", "استراتيجية", "عامل"])
    has_action = any(word in response for word in ["افعل", "تواصل", "استثمر", "حلل", "ابدأ", "قدم", "تصرف", "خفض", "حسن", "ركز"])
    has_analysis = any(word in response for word in ["لأن", "بسبب", "تحليل", "بيانات", "سبب", "نتيجة", "مؤشر", "نسبة"])
    
    if has_plan:
        score += 1
        print("   🟢 (قدم خطة)")
    if has_action:
        score += 1
        print("   🟢 (حدد إجراءات)")
    if has_analysis:
        score += 1
        print("   🟢 (حلل الموقف)")

print(f"\n{'='*60}")
print(f"🧠 نقاط العبقرية الاستراتيجية: {score} / 15")
if score == 15:
    print("🦅 نوح: عبقري استراتيجي!")
elif score >= 10:
    print("🦅 نوح: ممتاز")
else:
    print("🦅 نوح: يحتاج تحسين")
print(f"{'='*60}")
